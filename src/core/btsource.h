/* ============================================================
   btsource.h — BT-источник основной прошивки (этап 8, шаг 2)

   Связка из теста 04: кольцевой буфер + адаптация тактов.
   Wrover = A2DP sink (слейв I2S), S3 = мастер.
   Вывод звука — через Player::playSample(), поэтому громкость,
   баланс, тембр (IIR) и VU-метр работают как у остальных источников.
   ============================================================ */
#ifndef BTSOURCE_H
#define BTSOURCE_H

#include <Arduino.h>

namespace btsource {

void start();        // запустить приём BT (плеер к этому моменту уже остановлен)
void stop();         // остановить приём (дёшево, если BT не был запущен)
void toggle();       // пауза/продолжение (для PR_TOGGLE)
bool running();      // приём запущен (даже если Wrover молчит)
bool active();       // данные реально идут (буфер не пуст)
uint32_t inserts();  // счётчик вставок (адаптация)
uint32_t drops();    // счётчик поглощённых кадров
uint32_t lost();     // потеряно байт при переполнении кольца

} // namespace btsource

#endif // BTSOURCE_H
